import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,readFileSync,writeFileSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import {chromium} from 'playwright';
import {setImmediate as nextTurn,setTimeout as delay} from 'node:timers/promises';
import {PickupBrowser} from '../browser.mjs';
import {Engine} from '../engine.mjs';

test('standalone CLI connects over real loopback CDP and leaves Chrome open',async t=>{
  const dir=mkdtempSync(join(tmpdir(),'pickup-cdp-'));
  const profile=join(dir,'profile');
  const context=await chromium.launchPersistentContext(profile,{channel:'chrome',headless:true,args:['--remote-debugging-address=127.0.0.1','--remote-debugging-port=0']});
  t.after(async()=>{await context.close();rmSync(dir,{recursive:true,force:true});});
  const port=Number(readFileSync(join(profile,'DevToolsActivePort'),'utf8').split('\n')[0]);
  const config=join(dir,'test.local.json');
  writeFileSync(config,JSON.stringify({cdp_endpoint:`http://127.0.0.1:${port}`,state_dir:'state',selectors:{bag_item:'[data-autom=bag-item]'}}));
  const {stdout}=await promisify(execFile)(process.execPath,['mac_receiver/shopping.mjs','check','--config',config],{cwd:new URL('../../',import.meta.url),timeout:15000});
  assert.deepEqual(JSON.parse(stdout),{status:'cdp_connected',browser_ready:true});
  const page=await context.newPage();
  await page.setContent('<h1>Chrome still running</h1>');
  assert.equal(await page.getByRole('heading').innerText(),'Chrome still running');
  const browser=new PickupBrowser({cdp_endpoint:`http://127.0.0.1:${port}`});await browser.start();
  const calls=[];let second;
  const secondTask=new Promise(resolve=>{second=resolve;});
  browser.prepare=async e=>{calls.push(e.event_id);if(calls.length===2)second();return 'awaiting_user';};browser.handoff=async()=>{};
  const engine=new Engine({state_dir:join(dir,'queue-state'),dry_run:false,queue_while_busy:true,release_on_task_tab_close:true},browser);
  const event=id=>({event_id:id,detected_at:new Date().toISOString(),product_url:'https://www.apple.com/shop/buy-iphone/iphone-duo/7.6-inch-display-256gb-star-white-unlocked'});
  engine.accept(event('first'));await nextTurn();await nextTurn();
  assert.equal(engine.accept(event('second')).body.status,'held');
  await browser.page.close();
  await Promise.race([secondTask,delay(3000).then(()=>{throw Error('tab close did not release queue');})]);
  await nextTurn();assert.deepEqual(calls,['first','second']);assert.equal(engine.state.active,'second');
  engine.accept(event('third'));
  await context.close();await delay(350);
  assert.deepEqual(calls,['first','second']);assert.equal(engine.state.active,'second');
});
